def joint_choice(frontiers, exposure, fixed=None):
    """Exact Cartesian product optimum; first pair wins fully equal ties."""
    if len(frontiers) != 2 or not np.isfinite(exposure) or exposure <= 0:
        raise ValueError("Need two frontiers and positive original exposure")
    fixed = fixed or dict(zip(COUNTS, (0, 0, 0), strict=True))
    arrays = [np.asarray([[r[k] for k in COUNTS] for r in rows], dtype=float) for rows in frontiers]
    offset = np.asarray([fixed[k] for k in COUNTS], dtype=float)
    for array in (*arrays, offset.reshape(1, 3)):
        if (
            array.ndim != 2
            or array.shape[1] != 3
            or not len(array)
            or not np.isfinite(array).all()
            or np.any(array < 0)
            or np.any(array != np.floor(array))
            or np.any(array[:, 0] > np.minimum(array[:, 1], array[:, 2]))
            or len(np.unique(array[:, 2])) != 1
        ):
            raise ValueError("Invalid or changing event cohort in policy frontier")
    a, b = arrays
    counts = a[:, None, :] + b[None, :, :] + offset
    tp, alerts, events = (counts[:, :, i] for i in range(3))
    precision = np.divide(tp, alerts, out=np.zeros_like(tp), where=alerts > 0)
    recall = np.divide(tp, events, out=np.zeros_like(tp), where=events > 0)
    f1 = np.divide(2 * tp, alerts + events, out=np.zeros_like(tp), where=(alerts + events) > 0)
    primary = np.minimum(np.minimum(precision / 0.9, recall / 0.9), 1)
    budget = (alerts - tp) / exposure <= 0.25
    supported = budget & (alerts >= 10)
    allowed = supported if supported.any() else budget
    indices = np.flatnonzero(allowed.ravel())
    if not len(indices):
        raise ValueError("No policy pair within the false-warning budget")
    order = np.lexsort(
        (
            -indices,
            precision.ravel()[indices],
            recall.ravel()[indices],
            f1.ravel()[indices],
            primary.ravel()[indices],
        )
    )
    i, j = np.unravel_index(indices[order[-1]], primary.shape)
    scores = pooled([frontiers[0][i], frontiers[1][j], fixed])
    scores["false_alerts_per_object_day"] = (scores["alerts"] - scores["true_alerts"]) / exposure
    return {
        "indices": [int(i), int(j)],
        "scores": scores,
        "status": "supported" if supported.any() and scores["eligible_episodes"] >= 10 else "low_support",
        "pairs_evaluated": int(primary.size),
        "pairs_within_budget": int(budget.sum()),
    }


def group_labels(pred):
    labels = pred.object_kind.fillna("__unknown__").astype(str)
    if labels.groupby(pred.object_id).nunique().gt(1).any():
        raise ValueError("Object kind changed within a policy period")
    return labels.to_numpy()


def exposure_days(pred):
    if not pred.source_time.eq(pred.as_of.dt.floor("h")).all():
        raise ValueError("Expected original held-hourly sources")
    return len(pred[["object_id", "source_time"]].drop_duplicates()) / 24


def apply_group_policy(pred, episodes, policies, shared):
    labels = group_labels(pred)
    result = np.zeros(len(pred))
    for group in np.unique(labels):
        selected = labels == group
        rows = pred.loc[selected].reset_index(drop=True)
        result[selected] = policy_alerts(rows, episodes, policies.get(group, shared))
    return result


def select_group_policies(pred, episodes, shared, archived_frontier):
    labels = group_labels(pred)
    frontiers, supports = [], {}
    for group in GROUPS:
        view = pred.loc[labels == group].reset_index(drop=True)
        _, options = select_gate_policy(view, episodes, exposure_days(view))
        frontiers.append(options)
        supports[group] = {
            "forecast_rows": len(view),
            "objects": int(view.object_id.nunique()),
            "eligible_episodes": options[0]["eligible_episodes"],
        }
    unknown = pred.loc[~np.isin(labels, GROUPS)].reset_index(drop=True)
    unknown_alerts = policy_alerts(unknown, episodes, shared)
    fixed = evaluator_for(unknown, episodes, 0.25, exposure_days(unknown)).evaluate(unknown_alerts, 0.5, 0.25)
    for left, right, full in zip(*frontiers, archived_frontier, strict=True):
        for key in ("capacity", "margin", "floor"):
            assert left[key] == right[key] == full[key]
        # Unknown groups must use each corresponding diagonal policy here;
        # their selected shared policy is fixed only in the joint search.
        unknown_diagonal = policy_alerts(unknown, episodes, full)
        diagonal_fixed = evaluator_for(unknown, episodes, 0.25, exposure_days(unknown)).evaluate(
            unknown_diagonal, 0.5, 0.25
        )
        assert all(left[k] + right[k] + diagonal_fixed[k] == full[k] for k in COUNTS)
    chosen = joint_choice(frontiers, exposure_days(pred), fixed)
    policies = {group: frontiers[g][chosen["indices"][g]] for g, group in enumerate(GROUPS)}
    for group, policy in policies.items():
        supports[group]["chosen_policy_warnings"] = policy["alerts"]
    replay = apply_group_policy(pred, episodes, policies, shared)
    actual = evaluator_for(pred, episodes, 0.25, exposure_days(pred)).evaluate(replay, 0.5, 0.25)
    assert all(actual[k] == chosen["scores"][k] for k in COUNTS)
    return {
        **chosen,
        "policies": policies,
        "supports": supports,
        "fixed_unknown_scores": fixed,
        "diagonal_exact_parity": True,
    }, dict(zip(GROUPS, frontiers, strict=True))


def evaluate(root, kind, fold, variants, frame, dense, episodes):
    directory, target = root / kind / fold, root / kind / fold / "result.json"
    if target.exists():
        result = read(target)
        if set(result["variants"]) != set(variants):
            raise ValueError("Cached result has different candidate variants")
        return result
    if fold.startswith("screen_"):
        base = Path("artifacts/research-v26") / kind / fold
        controls = read(base / "result.json")
    else:
        controls = evaluate_models(root / "controls", kind, fold, frame, dense, episodes)
        base = root / "controls" / kind / fold
    directory.mkdir(parents=True, exist_ok=True)
    rows = {}
    for variant in variants:
        policy_pred = pd.read_parquet(base / f"{variant}-policy.parquet")
        test = pd.read_parquet(base / f"{variant}-test.parquet")
        shared = controls["arms"][variant]["policy"]
        print("START group policy", kind, fold, variant, flush=True)
        chosen, frontiers = select_group_policies(
            policy_pred, episodes, shared, read(base / f"{variant}-frontier.json")
        )
        test["candidate_alert"] = apply_group_policy(test, episodes, chosen["policies"], shared)
        exposure = exposure_days(test)
        assert exposure == controls["exposure_days"]
        evaluator = evaluator_for(test, episodes, 0.25, exposure)
        shared_alerts = policy_alerts(test, episodes, shared)
        assert evaluator.evaluate(shared_alerts, 0.5, 0.25) == controls["arms"][variant]["scores"]
        np.testing.assert_array_equal(shared_alerts, test.alert)
        scores = evaluator.evaluate(test.candidate_alert, 0.5, 0.25)
        subgroup = {}
        for group, view in test.groupby("object_kind", dropna=False):
            view = view.reset_index(drop=True)
            subgroup[str(group)] = evaluator_for(view, episodes, 0.25, exposure_days(view)).evaluate(
                view.candidate_alert, 0.5, 0.25
            )
        combined = pooled(list(subgroup.values()))
        assert all(combined[k] == scores[k] for k in COUNTS)
        test.to_parquet(directory / f"{variant}-test.parquet", index=False)
        write_json(directory / f"{variant}-group-frontiers.json", frontiers)
        rows[variant] = {
            "scores": scores,
            "shared_control": controls["arms"][variant]["scores"],
            **{key: controls[key] for key in ("global_control", "calibration_control", "reference")},
            "selection": chosen,
            "shared_policy": shared,
            "subgroup_scores": subgroup,
            "exposure_days": exposure,
            "unchanged_forecast_values": True,
            "same_episode_cohort": True,
            "shared_policy_exact_replay": True,
        }
        assert all(
            scores["eligible_episodes"] == rows[variant][key]["eligible_episodes"] for key in REFERENCE_KEYS
        )
        print("DONE group policy", kind, fold, variant, scores, flush=True)
    result = {"kind": kind, "fold": fold, "variants": rows}
    write_json(target, result)
    return result


def lock_plan(root):
    sources = [
        PROCESSED / "features-channel-novelty.parquet",
        PROCESSED / "features-dense-channel-novelty.parquet",
        PROCESSED / "episodes.parquet",
        Path("artifacts/object_kind_error_audit.json"),
        Path("artifacts/research-v26/plan.json"),
        Path("artifacts/research-v26/report.json"),
    ]
    for kind in KINDS:
        for fold in (*FOLDS, *STRESS):
            weights, metadata, saved = source_files(kind, fold)
            sources.extend([weights, metadata, *saved.values()])
            if fold.startswith("screen_"):
                base = Path("artifacts/research-v26") / kind / fold
                sources.append(base / "result.json")
                for variant in VARIANTS:
                    sources.extend(base / f"{variant}-{p}.parquet" for p in ("policy", "test"))
                    sources.append(base / f"{variant}-frontier.json")
                for group in GROUPS:
                    meta = base / "groups" / group / "fit.json"
                    sources.extend([meta, Path(read(meta)["weights_file"])])
            if kind == "access":
                sources.append(Path("artifacts/research-v20/access") / fold / "result.json")
            elif kind == "fault":
                sources.append(Path("artifacts/research-v19/fault") / fold / "result.json")
            else:
                sources.append(Path("artifacts/research-v13-policy") / f"fire-{fold}.json")
    code = {
        Path(__file__),
        *(
            Path(f.__code__.co_filename)
            for f in (
                EventEvaluator.__init__,
                evaluate_models,
                select_gate_policy,
                evaluator_for,
                policy_alerts,
                source_files,
                primary_score,
            )
        ),
    }
    code.update(Path(p) for p in read(Path("artifacts/research-v26/plan.json"))["code_hashes"])
    plan = json.loads(
        json.dumps(
            {
                **PLAN,
                "source_hashes": {str(p): sha256(p) for p in sources},
                "code_hashes": {str(p): sha256(p) for p in sorted(code)},
            }
        )
    )
    root.mkdir(parents=True, exist_ok=True)
    target = root / "plan.json"
    if target.exists():
        if read(target) != plan:
            raise ValueError("Study inputs/code changed; use a new study directory")
    else:
        write_json(target, plan)


def run(root, stage):
    lock_plan(root)
    episodes = pd.read_parquet(
        PROCESSED / "episodes.parquet", filters=[("start_ts", "<", pd.Timestamp("2026-06-01"))]
    )
    if stage == "screen":
        selection = {}
        for kind in KINDS:
            rows = [
                evaluate(root, kind, fold, VARIANTS, None, None, episodes[episodes.kind.eq(kind)])
                for fold in ("screen_1", "screen_2")
            ]
            candidates = {}
            for variant in VARIANTS:
                totals = {
                    key: pooled([row["variants"][variant][key] for row in rows])
                    for key in ("scores", *REFERENCE_KEYS)
                }
                candidate = totals["scores"]
                candidates[variant] = {
                    **totals,
                    "passed_screen": all(
                        primary_score(candidate) > 1.05 * primary_score(totals[key])
                        and candidate["f1"] >= totals[key]["f1"]
                        for key in REFERENCE_KEYS
                    ),
                }
            eligible = [name for name in VARIANTS if candidates[name]["passed_screen"]]
            winner = (
                max(
                    eligible,
                    key=lambda name: tuple(
                        candidates[name]["scores"][key]
                        for key in ("primary_score", "f1", "recall", "precision")
                    ),
                )
                if eligible
                else None
            )
            selection[kind] = {
                "variants": candidates,
                "selected_variant": winner,
                "passed_screen": winner is not None,
            }
            write_json(root / "selection.json", selection)
            print("SELECT group policy", kind, selection[kind], flush=True)
        return
    selection = read(root / "selection.json")
    if set(selection) != set(KINDS):
        raise ValueError("Finish all screening first")
    frame = dense = None
    if any(row["passed_screen"] for row in selection.values()):
        frame = pd.read_parquet(PROCESSED / "features-channel-novelty.parquet")
        dense = pd.read_parquet(PROCESSED / "features-dense-channel-novelty.parquet")
        assert all(f.as_of.lt(pd.Timestamp("2026-06-01")).all() for f in (frame, dense))
    report = {}
    for kind, selected in selection.items():
        if not selected["passed_screen"]:
            report[kind] = {"selection": selected, "research_eligible": False, "status": "screen_failed"}
            continue
        variant = selected["selected_variant"]
        results = [
            evaluate(root, kind, fold, (variant,), frame, dense, episodes[episodes.kind.eq(kind)])
            for fold in ("confirmation", *STRESS)
        ]
        rows = [row["variants"][variant] for row in results]
        may, stress = rows[0], pooled([row["scores"] for row in rows[1:]])
        passed_may = all(
            primary_score(may["scores"]) > primary_score(may[key])
            and may["scores"]["f1"] >= 0.95 * may[key]["f1"]
            for key in REFERENCE_KEYS
        )
        passed_stress = all(
            primary_score(stress) > 1.05 * primary_score(pooled([row[key] for row in rows[1:]]))
            and stress["f1"] >= pooled([row[key] for row in rows[1:]])["f1"]
            and all(row["scores"]["f1"] >= 0.9 * row[key]["f1"] for row in rows[1:])
            for key in REFERENCE_KEYS
        )
        results = [read(root / kind / fold / "result.json") for fold in ("screen_1", "screen_2")] + results
        report[kind] = {
            "selection": selected,
            "periods": results,
            "five_period_pooled": {
                key: pooled([row["variants"][variant][key] for row in results])
                for key in ("scores", *REFERENCE_KEYS)
            },
            "passed_may": passed_may,
            "passed_stress": passed_stress,
            "research_eligible": bool(passed_may and passed_stress),
            "automatic_activation": False,
        }
        write_json(root / "report.json", report)
        print(
            "REPORT group policy",
            kind,
            {key: value for key, value in report[kind].items() if key != "periods"},
            flush=True,
        )
    write_json(root / "report.json", report)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("artifacts/research-v27"))
    parser.add_argument("--stage", choices=("screen", "confirm"), required=True)
    args = parser.parse_args()
    run(args.output, args.stage)
