def table(headers, rows, widths):
    t = doc.add_table(rows=1, cols=len(headers))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    for i, w in enumerate(widths):
        t.columns[i].width = Inches(w)
    for i, x in enumerate(headers):
        t.rows[0].cells[i].text = str(x)
    for row in rows:
        for c, x in zip(t.add_row().cells, row, strict=True):
            c.text = str(x)
    for ri, row in enumerate(t.rows):
        trPr = row._tr.get_or_add_trPr()
        cant = OxmlElement("w:cantSplit")
        trPr.append(cant)
        if ri == 0:
            repeat = OxmlElement("w:tblHeader")
            trPr.append(repeat)
        for ci, c in enumerate(row.cells):
            c.width = Inches(widths[ci])
            c.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            pr = c._tc.get_or_add_tcPr()
            borders = OxmlElement("w:tcBorders")
            for side in ("top", "left", "bottom", "right"):
                e = OxmlElement("w:" + side)
                e.set(qn("w:val"), "single")
                e.set(qn("w:sz"), "4")
                e.set(qn("w:color"), "D9D9D9")
                borders.append(e)
            pr.append(borders)
            shading = OxmlElement("w:shd")
            shading.set(qn("w:fill"), "273B40" if ri == 0 else "F2F5F6" if ri % 2 == 0 else "FFFFFF")
            pr.append(shading)
            margins = OxmlElement("w:tcMar")
            for side in ("top", "left", "bottom", "right"):
                e = OxmlElement("w:" + side)
                e.set(qn("w:w"), "85")
                e.set(qn("w:type"), "dxa")
                margins.append(e)
            pr.append(margins)
            for para in c.paragraphs:
                para.paragraph_format.space_after = Pt(2)
                para.paragraph_format.line_spacing = 1.05
                if len(rows) <= 6:
                    para.paragraph_format.keep_with_next = ri < len(t.rows) - 1
                if ci > 0 and len(str(c.text)) < 35:
                    para.alignment = WD_ALIGN_PARAGRAPH.CENTER
                for run in para.runs:
                    run.font.size = Pt(10)
                    run.bold = ri == 0
                    run.font.color.rgb = RGBColor(255, 255, 255) if ri == 0 else RGBColor(0, 0, 0)
    p("")
    return t


